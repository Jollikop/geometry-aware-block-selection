#!/usr/bin/env python3
"""Prediction-partition control table (Table 3, Appendix D.3).

Reads the frozen block-diagonal predictions (current pipelines) and the
prediction-only controls E1 ((R)BT-SVGP donors with an Algorithm-1 prediction
partition) and E2 ((S)BT-SVGP donors with a uniformly random prediction
partition). Writes a LaTeX table and a CSV of paired per-seed differences.
Run from any directory; inputs are read only.
"""
import csv
import glob
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CUR = ROOT / "output/results/hard_pic_predict_full_v1_20261003"
CTRL = ROOT / "output/results/partition_controls_download_20261006_v1"
TABLE = ROOT / "Report/tables/partition_controls.tex"
CSV = ROOT / "Report/Results/partition_controls_summary.csv"
KERNELS = [("rbf", "RBF"), ("amplitude-rbf", "Amplitude-RBF")]
DATASETS = [("pol", "Pol"), ("superconductivity", "Supercond."),
            ("kin40k", "Kin40k"), ("protein", "Protein")]
MS = [64, 128, 256, 512]


def load(root):
    out = {}
    for f in glob.glob(str(root / "hard/svgp/**/prediction.json"), recursive=True):
        p = json.loads(Path(f).read_text())
        if p.get("valid") is not True:
            raise ValueError(f"invalid prediction: {f}")
        out[(p["kernel"], p["dataset"], p["M"], p["method"], p["seed"])] = p
    return out


def mean_se(values):
    n = len(values)
    m = sum(values) / n
    s = math.sqrt(sum((v - m) ** 2 for v in values) / (n - 1) / n)
    return m, s


def fmt(m, s):
    text = f"{m:.3f}".replace("0.", ".", 1)
    return f"{text}({max(1, round(s * 1000))})"


def main():
    cur, e1, e2 = load(CUR), load(CTRL / "E1"), load(CTRL / "E2")
    rows, lines = [], []
    for kern, kname in KERNELS:
        for ds, dname in DATASETS:
            for M in MS:
                seeds = sorted(k[4] for k in e1 if k[:3] == (kern, ds, M))
                if len(seeds) != 10:
                    raise ValueError(f"expected ten seeds: {kern} {ds} {M}")
                nll = lambda d, meth: [d[(kern, ds, M, meth, s)]["nll"] for s in seeds]
                r_cur, s_cur = nll(cur, "RBT-SVGP"), nll(cur, "SBT-SVGP")
                r_sel, s_rnd = nll(e1, "RBT-SVGP"), nll(e2, "SBT-SVGP")
                for d in (e1, e2):
                    meth = "RBT-SVGP" if d is e1 else "SBT-SVGP"
                    for s in seeds:
                        if d[(kern, ds, M, meth, s)]["rmse"] != cur[(kern, ds, M, meth, s)]["rmse"]:
                            raise ValueError("prediction partition changed the RMSE")
                diffs = {
                    "current": mean_se([a - b for a, b in zip(s_cur, r_cur)]),
                    "same_selected": mean_se([a - b for a, b in zip(s_cur, r_sel)]),
                    "same_random": mean_se([a - b for a, b in zip(s_rnd, r_cur)]),
                }
                for key, (m, s) in diffs.items():
                    rows.append(dict(kernel=kern, dataset=ds, M=M, comparison=key,
                                     metric="nll_SBT_minus_RBT", n=10, mean=m, sem=s))
                lines.append(f"{kname} & {dname} & {M} & "
                             + " & ".join(fmt(*diffs[k]) for k in
                                          ("current", "same_selected", "same_random"))
                             + r" \\")
            lines.append(r"\addlinespace[1pt]")
    lines.pop()
    CSV.parent.mkdir(parents=True, exist_ok=True)
    with CSV.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    TABLE.write_text("\n".join([
        "% Generated by Report/notes/build_partition_controls_table.py",
        r"\begin{table}[!ht]",
        r"\caption{Prediction-partition control on the configurations of Figure~\ref{fig:svgp-final}: "
        r"test NLL of (S)BT-SVGP minus that of (R)BT-SVGP (negative favours (S)BT-SVGP), mean (SE) "
        r"over ten paired seeds. Current: each donor with its own \(\mathcal P_{\mathrm{pred}}\), "
        r"as in Figure~\ref{fig:svgp-final}. Common selected rule: both donors with \(\mathcal P_{\mathrm{pred}}\) "
        r"from Algorithm~\ref{alg:sbt} at their saved parameters. Common random rule: both donors with a uniformly "
        r"random partition into blocks of 500. The common selected rule applies Algorithm~\ref{alg:sbt} separately "
        r"at each donor's saved parameters; block memberships need not coincide. Under the common random rule the "
        r"donors do not share an index permutation: (R)BT-SVGP keeps the random partition it was trained with, and "
        r"(S)BT-SVGP receives an independent uniformly random permutation in each paired seed. "
        r"Donor parameters are frozen; RMSE is unchanged.}",
        r"\label{tab:partition-controls}",
        r"\centering\footnotesize",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{@{}llrrrr@{}}",
        r"\toprule",
        r"Kernel & Dataset & \(M\) & Current & \begin{tabular}[b]{@{}r@{}}Common\\selected rule\end{tabular} "
        r"& \begin{tabular}[b]{@{}r@{}}Common\\random rule\end{tabular} \\",
        r"\midrule",
        *lines,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        ""]))
    print(f"wrote {TABLE.relative_to(ROOT)} and {CSV.relative_to(ROOT)} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
