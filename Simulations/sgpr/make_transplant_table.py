#!/usr/bin/env python3
"""Consolidate the four validated SGPR transplant summaries for the paper."""
from __future__ import annotations

import argparse
import csv
import math
import shutil
from pathlib import Path


KERNELS = ("rbf", "gibbs", "matern52", "amplitude-rbf")
KERNEL_LABELS = {
    "rbf": "RBF",
    "gibbs": "Gibbs (non-stationary)",
    "matern52": "Mat\\'ern-5/2",
    "amplitude-rbf": "Amplitude-RBF",
}
METHODS = ("SGPR", "T-SGPR", "RBT-SGPR", "SBT-SGPR")
FIELDS = (
    ("donor_complete_rmse", 3),
    ("donor_complete_nll", 3),
    ("donor_sparse_nll", 3),
    ("transplant_sgpr_rmse", 3),
    ("transplant_sgpr_nll", 3),
    ("delta_sgpr_elbo_n", 4),
)


def parse_args() -> argparse.Namespace:
    project = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--transplant-root",
        type=Path,
        required=True,
        help="directory containing <kernel>/summary.csv",
    )
    parser.add_argument(
        "--tex-out",
        type=Path,
        default=project / "Report/tables/kin40k_sgpr_transplant.tex",
    )
    parser.add_argument(
        "--results-out-dir",
        type=Path,
        default=project / "Report/Results",
        help="copy the four machine-readable summaries here",
    )
    return parser.parse_args()


def load_summary(path: Path) -> dict[str, dict[str, str]]:
    with path.open(newline="") as stream:
        rows = list(csv.DictReader(stream))
    by_method = {row.get("donor_method", ""): row for row in rows}
    if set(by_method) != set(METHODS) or len(rows) != len(METHODS):
        raise SystemExit(f"{path}: expected exactly {METHODS}")
    for method, row in by_method.items():
        if int(row.get("n_seeds", 0)) != 10:
            raise SystemExit(f"{path}: {method} does not contain ten seeds")
        for field, _ in FIELDS:
            for suffix in ("mean", "sem"):
                value = float(row[f"{field}_{suffix}"])
                if not math.isfinite(value):
                    raise SystemExit(
                        f"{path}: non-finite {field}_{suffix} for {method}"
                    )
    return by_method


def cell(row: dict[str, str], field: str, digits: int) -> str:
    return (
        f"{float(row[f'{field}_mean']):.{digits}f} "
        f"({float(row[f'{field}_sem']):.{digits}f})"
    )


def write_tex(path: Path, summaries: dict[str, dict[str, dict[str, str]]]) -> None:
    lines = [
        "% Generated by Simulations/sgpr/make_transplant_table.py.",
        "\\begin{table*}[t]",
        "\\caption{Kin40k hyperparameter transplant (\\(5000/2000\\) "
        "train/test points, \\(M=256\\)). Donors pass the v22 convergence "
        "gate. Their kernel and noise parameters are then frozen and only "
        "the inducing locations are re-optimised under the SGPR trace bound "
        "until convergence, with 10000 SciPy L-BFGS-B iterations as a hard maximum. "
        "Entries are mean (standard error) over ten seeds. Lower RMSE/NLL "
        "and larger \\(\\Delta\\mathrm{ELBO}/N\\) are better.}",
        "\\label{tab:kin40k-sgpr-transplant}",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\renewcommand{\\arraystretch}{0.94}",
        "\\begin{tabular}{@{}lrrrrrr@{}}",
        "\\toprule",
        "& \\multicolumn{2}{c}{Donor, own predictor} "
        "& \\multicolumn{1}{c}{Donor as sparse} "
        "& \\multicolumn{2}{c}{After SGPR transplant} & \\\\",
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-4}\\cmidrule(lr){5-6}",
        "Donor bound & RMSE & NLL & NLL & RMSE & NLL "
        "& \\(\\Delta\\mathrm{ELBO}/N\\) \\\\",
    ]
    for kernel in KERNELS:
        lines.append("\\midrule")
        lines.append(
            f"\\multicolumn{{7}}{{@{{}}l}}{{\\textbf{{{KERNEL_LABELS[kernel]}}}}} \\\\"
        )
        for method in METHODS:
            values = [cell(summaries[kernel][method], *field) for field in FIELDS]
            if method == "SBT-SGPR":
                method_cell = "\\textbf{SBT-SGPR}"
                values = [f"\\textbf{{{value}}}" for value in values]
            else:
                method_cell = method
            lines.append(" & ".join((method_cell, *values)) + " \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))


def main() -> None:
    args = parse_args()
    summaries = {}
    args.results_out_dir.mkdir(parents=True, exist_ok=True)
    for kernel in KERNELS:
        source = args.transplant_root / kernel / "summary.csv"
        summaries[kernel] = load_summary(source)
        destination = (
            args.results_out_dir
            / f"kin40k_sgpr_transplant_{kernel.replace('-', '_')}_summary.csv"
        )
        shutil.copyfile(source, destination)
        print(f"copied {destination}")
    write_tex(args.tex_out, summaries)
    print(f"wrote {args.tex_out}")


if __name__ == "__main__":
    main()
